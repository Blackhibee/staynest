const menuToggle = document.querySelector('.menu-toggle');
const mobileMenu = document.querySelector('.mobile-menu');
const propertyGrid = document.getElementById('propertyGrid');
const pagination = document.getElementById('pagination');
const resultCount = document.getElementById('resultCount');
const listingSearch = document.getElementById('listingSearch');
const searchInput = document.getElementById('searchInput');
const typeFilter = document.getElementById('typeFilter');
const sortFilter = document.getElementById('sortFilter');
const activeFilterLabel = document.getElementById('activeFilterLabel');

const allProperties = Object.entries(propertyData).flatMap(([city, properties]) =>
  properties.map((property, index) => ({
    ...property,
    id: `${city.toLowerCase().replaceAll(' ', '-')}-${index + 1}`,
    location: `${property.location}, ${city}`,
    propertyType: property.tag.toLowerCase().includes('villa') ? 'Villa' : property.tag.toLowerCase().includes('loft') ? 'Loft' : property.tag.toLowerCase().includes('house') ? 'House' : 'Apartment',
    bedrooms: index % 3 + 1,
    bathrooms: index % 2 + 1,
    guests: (index % 3 + 1) * 2,
    amenities: ['Wi-Fi', ...property.amenities.map((amenity) => amenity === 'Swimming Pool' ? 'Swimming pool' : amenity === 'Beachfront' ? 'Beach access' : 'Workspace')]
  }))
);

let currentPage = 1;
const pageSize = 6;
let filteredProperties = allProperties;

const renderPropertyCard = (property) => `
  <article class="property-card" data-property-id="${property.id}">
    <div class="image-wrap"><img src="${property.image}" alt="${property.name}" loading="lazy" /><button class="fav-btn" type="button" aria-label="Save ${property.name}" aria-pressed="false">♡</button></div>
    <div class="property-body"><div class="top-row"><h3>${property.name}</h3><span class="rating-badge">★ ${property.rating}</span></div>
      <p class="location">${property.location}</p><p class="specs">${property.bedrooms} bed · ${property.bathrooms} bath · ${property.guests} guests</p>
      <div class="amenities">${property.amenities.slice(0, 3).map((amenity) => `<span>${amenity}</span>`).join('')}</div>
      <div class="bottom-row"><div><strong>$${property.price}</strong><span>/ night</span></div><span class="tag">${property.propertyType}</span></div>
    </div>
  </article>`;

const renderPagination = () => {
  const pageCount = Math.ceil(filteredProperties.length / pageSize);
  if (!pagination) return;
  pagination.innerHTML = pageCount <= 1 ? '' : `<button type="button" data-page="prev" ${currentPage === 1 ? 'disabled' : ''}>Previous</button>${Array.from({ length: pageCount }, (_, i) => `<button type="button" data-page="${i + 1}" class="${currentPage === i + 1 ? 'active' : ''}">${i + 1}</button>`).join('')}<button type="button" data-page="next" ${currentPage === pageCount ? 'disabled' : ''}>Next</button>`;
  pagination.querySelectorAll('button').forEach((button) => button.addEventListener('click', () => {
    const target = button.dataset.page;
    currentPage = target === 'prev' ? currentPage - 1 : target === 'next' ? currentPage + 1 : Number(target);
    renderListings();
  }));
};

const renderListings = () => {
  const start = (currentPage - 1) * pageSize;
  const visible = filteredProperties.slice(start, start + pageSize);
  propertyGrid.innerHTML = visible.length ? visible.map(renderPropertyCard).join('') : '<div class="empty-state">No homes match those filters. Try a different search.</div>';
  resultCount.textContent = filteredProperties.length;
  renderPagination();
  propertyGrid.querySelectorAll('.fav-btn').forEach((button) => button.addEventListener('click', (event) => {
    event.stopPropagation();
    button.classList.toggle('is-active');
    button.setAttribute('aria-pressed', button.classList.contains('is-active'));
    button.textContent = button.classList.contains('is-active') ? '♥' : '♡';
  }));
  propertyGrid.querySelectorAll('.property-card').forEach((card) => card.addEventListener('click', () => {
    const property = allProperties.find((item) => item.id === card.dataset.propertyId);
    if (property) {
      sessionStorage.setItem(`staynest-property-${property.id}`, JSON.stringify(property));
      window.location.href = `property.html?id=${encodeURIComponent(property.id)}`;
    }
  }));
};

const applyFilters = () => {
  const search = searchInput.value.trim().toLowerCase();
  const type = typeFilter.value;
  const amenities = Array.from(document.querySelectorAll('.filter-pill input:checked')).map((input) => input.value);
  filteredProperties = allProperties.filter((property) =>
    (!search || `${property.name} ${property.location}`.toLowerCase().includes(search)) &&
    (type === 'all' || property.propertyType === type) &&
    amenities.every((amenity) => property.amenities.includes(amenity))
  );
  if (sortFilter.value === 'price-low') filteredProperties.sort((a, b) => a.price - b.price);
  if (sortFilter.value === 'price-high') filteredProperties.sort((a, b) => b.price - a.price);
  if (sortFilter.value === 'rating') filteredProperties.sort((a, b) => b.rating - a.rating);
  currentPage = 1;
  activeFilterLabel.textContent = type === 'all' ? 'All stays' : `${type}s only`;
  renderListings();
};

// Modal helpers
const modalRoot = document.getElementById('propertyModal');
const openPropertyModal = (property, stateName) => {
  if (!modalRoot) return;
  const title = modalRoot.querySelector('#modalTitle');
  const sub = modalRoot.querySelector('#modalSub');
  const price = modalRoot.querySelector('#modalPrice');
  const rating = modalRoot.querySelector('#modalRating');
  const amenities = modalRoot.querySelector('#modalAmenities');
  const gallery = modalRoot.querySelector('#modalGallery');
  const desc = modalRoot.querySelector('#modalDescription');

  title.textContent = property.name || '';
  sub.textContent = stateName ? `${property.location || ''}, ${stateName}` : property.location || '';
  price.textContent = `$${property.price} / night`;
  rating.textContent = `★ ${property.rating}`;
  desc.textContent = property.tag ? property.tag : '';

  const imgs = property.images && property.images.length ? property.images : [property.image].filter(Boolean);
  gallery.innerHTML = `
    <img class="main-img" src="${imgs[0]}" alt="${property.name}" />
    <div class="thumbs">
      ${imgs.map((src, i) => `<img src="${src}" data-src="${src}" data-i="${i}" alt="thumb-${i}" />`).join('')}
    </div>
  `;

  amenities.innerHTML = (property.amenities || []).map((a) => `<span>${a}</span>`).join('');

  // thumbnail click => swap main image
  gallery.querySelectorAll('.thumbs img').forEach((tn) => {
    tn.addEventListener('click', () => {
      const main = gallery.querySelector('.main-img');
      if (main && tn.dataset.src) main.src = tn.dataset.src;
    });
  });

  modalRoot.classList.add('open');
  modalRoot.setAttribute('aria-hidden', 'false');
};

const closePropertyModal = () => {
  if (!modalRoot) return;
  modalRoot.classList.remove('open');
  modalRoot.setAttribute('aria-hidden', 'true');
};

// modal close handlers
if (modalRoot) {
  modalRoot.querySelectorAll('[data-action="close"]').forEach((el) => {
    el.addEventListener('click', closePropertyModal);
  });

  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') closePropertyModal();
  });
}

if (menuToggle && mobileMenu) {
  menuToggle.addEventListener('click', () => {
    const isOpen = mobileMenu.classList.toggle('open');
    menuToggle.setAttribute('aria-expanded', String(isOpen));
  });
}

listingSearch.addEventListener('submit', (event) => {
  event.preventDefault();
  applyFilters();
});
[typeFilter, sortFilter].forEach((control) => control.addEventListener('change', applyFilters));
document.querySelectorAll('.filter-pill input').forEach((input) => input.addEventListener('change', applyFilters));
renderListings();
